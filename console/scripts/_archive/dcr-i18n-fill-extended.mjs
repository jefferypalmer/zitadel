function setPath(obj, path, value) {
  const parts = path.split('.');
  let cur = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    const k = parts[i];
    if (typeof cur[k] !== 'object' || cur[k] === null || Array.isArray(cur[k])) cur[k] = {};
    cur = cur[k];
  }
  cur[parts.at(-1)] = value;
}

async function main() {
  const en = JSON.parse(await readFile(join(I18N_DIR, 'en.json'), 'utf8'));
  const enDcr = en.DESCRIPTIONS.DCR;
  for (const [locale, flat] of Object.entries(T)) {
    const targetPath = join(I18N_DIR, locale + '.json');
    const data = JSON.parse(await readFile(targetPath, 'utf8'));
    let writes = 0;
    for (const [k, v] of Object.entries(flat)) {
      // Only overwrite when current value equals the EN passthrough.
      // If a translator already replaced it with a non-passthrough,
      // keep theirs.
      const enVal = k.split('.').reduce((x, p) => x?.[p], enDcr);
      const cur = k.split('.').reduce((x, p) => x?.[p], data.DESCRIPTIONS.DCR);
      if (cur !== enVal && cur !== undefined) continue;
      setPath(data.DESCRIPTIONS.DCR, k, v);
      writes++;
    }
    await writeFile(targetPath, JSON.stringify(data, null, 2) + '\n', 'utf8');
    process.stderr.write(`wrote ${locale} (${writes} keys)\n`);
  }
}

main().catch(err => { process.stderr.write(`fatal: ${err.message}\n`); process.exit(1); });
