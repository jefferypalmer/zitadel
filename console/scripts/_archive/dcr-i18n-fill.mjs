function setPath(obj, path, value) {
  const parts = path.split('.');
  let cur = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    const k = parts[i];
    if (typeof cur[k] !== 'object' || cur[k] === null || Array.isArray(cur[k])) {
      cur[k] = {};
    }
    cur = cur[k];
  }
  cur[parts.at(-1)] = value;
}

async function main() {
  const en = JSON.parse(await readFile(join(I18N_DIR, 'en.json'), 'utf8'));
  for (const [locale, flat] of Object.entries(T)) {
    const targetPath = join(I18N_DIR, locale + '.json');
    const target = JSON.parse(await readFile(targetPath, 'utf8'));
    // Build a translations object whose paths under DESCRIPTIONS.DCR match flat.
    const translations = { DESCRIPTIONS: { DCR: {} } };
    for (const [subPath, value] of Object.entries(flat)) {
      setPath(translations.DESCRIPTIONS.DCR, subPath, value);
    }
    const merged = mergeTranslations(en, target, translations);
    await writeFile(targetPath, JSON.stringify(merged, null, 2) + '\n', 'utf8');
    process.stderr.write(`wrote ${locale} (${Object.keys(flat).length} keys)\n`);
  }
}

main().catch(err => {
  process.stderr.write(`fatal: ${err.message}\n`);
  process.exit(1);
});
